        "import os\n",
        "import random\n",
        "from typing import TypedDict, Literal\n",
        "from langchain_core.messages import HumanMessage, AIMessage, BaseMessage\n",
        "from langgraph.graph import StateGraph, END\n",
        "\n",
        "# 1. Define the State\n",
        "# This is the \"schema\" of our shared memory.\n",
        "class AgentState(TypedDict):\n",
        "    \"\"\"\n",
        "    Represents the state of our agentic workflow.\n",
        "    \n",
        "    Attributes:\n",
        "        ticket_query (str): The initial user request.\n",
        "        messages (list[BaseMessage]): History of interactions or scratchpad notes.\n",
        "        route_decision (Literal[\"AI_agent\", \"human\", \"\"]): The outcome of the triage.\n",
        "    \"\"\"\n",
        "    ticket_query: str\n",
        "    messages: list[BaseMessage]\n",
        "    route_decision: Literal[\"AI_agent\", \"human\", \"\"]\n",
        "\n",
        "\n",
        "# 2. Define Nodes (The Workers)\n",
        "\n",
        "def triage_node(state: AgentState) -> dict:\n",
        "    \"\"\"\n",
        "    Analyzes the ticket_query and decides the routing.\n",
        "    In production, this would use an LLM with structured output.\n",
        "    Here, we simulate it for predictable local execution.\n",
        "    \"\"\"\n",
        "    query = state[\"ticket_query\"].lower()\n",
        "    \n",
        "    # Simulated logic: if it mentions \"billing\" or \"refund\", send to human.\n",
        "    if \"billing\" in query or \"refund\" in query:\n",
        "        decision: Literal[\"human\", \"AI_agent\"] = \"human\"\n",
        "    else:\n",
        "        decision = \"AI_agent\"\n",
        "        \n",
        "    # We return a dictionary mapping state keys to their NEW values.\n",
        "    # LangGraph will automatically merge these updates into the current state.\n",
        "    return {\n",
        "        \"route_decision\": decision,\n",
        "        \"messages\": [AIMessage(content=f\"Triage complete: routing to {decision}.\")]\n",
        "    }\n",
        "\n",
        "def ai_agent_node(state: AgentState) -> dict:\n",
        "    \"\"\"\n",
        "    Handles general inquiries autonomously.\n",
        "    \"\"\"\n",
        "    # In reality, you'd call an LLM here.\n",
        "    response_msg = AIMessage(content=\"AI Agent: I can help you reset your password or configure your dashboard. What do you need?\")\n",
        "    \n",
        "    return {\n",
        "        # Notice we don't update route_decision, only messages.\n",
        "        # By default, state updates overwrite. If messages were defined with `operator.add` in TypedDict (Annotated), they would append.\n",
        "        # For simplicity here without Annotated, we manually append.\n",
        "        \"messages\": state.get(\"messages\", []) + [response_msg]\n",
        "    }\n",
        "\n",
        "def human_escalation_node(state: AgentState) -> dict:\n",
        "    \"\"\"\n",
        "    Routes complex/sensitive issues to a human queue.\n",
        "    \"\"\"\n",
        "    response_msg = AIMessage(content=\"System: Ticket escalated to human support queue due to billing/refund keywords.\")\n",
        "    return {\n",
        "        \"messages\": state.get(\"messages\", []) + [response_msg]\n",
        "    }\n",
        "\n",
        "\n",
        "# 3. Define Conditional Edges (The Logic)\n",
        "\n",
        "def route_after_triage(state: AgentState) -> Literal[\"human_node\", \"ai_node\"]:\n",
        "    \"\"\"\n",
        "    Inspects the state after triage and dictates the next node.\n",
        "    \n",
        "    Returns the string name of the next node to execute.\n",
        "    \"\"\"\n",
        "    if state[\"route_decision\"] == \"human\":\n",
        "        return \"human_node\"\n",
        "    else:\n",
        "        return \"ai_node\"\n",
        "\n",
        "\n",
        "# 4. Build and Compile the Graph\n",
        "\n",
        "def build_graph():\n",
        "    # Initialize graph with the State definition\n",
        "    workflow = StateGraph(AgentState)\n",
        "\n",
        "    # Add all nodes. (name_of_node, function_to_execute)\n",
        "    workflow.add_node(\"triage\", triage_node)\n",
        "    workflow.add_node(\"ai_node\", ai_agent_node)\n",
        "    workflow.add_node(\"human_node\", human_escalation_node)\n",
        "\n",
        "    # Define standard start edge (where execution begins)\n",
        "    workflow.set_entry_point(\"triage\")\n",
        "\n",
        "    # Define conditional edge from triage to either ai_node or human_node\n",
        "    workflow.add_conditional_edges(\n",
        "        \"triage\",            # Source node\n",
        "        route_after_triage,  # Routing function\n",
        "        {                    # Mapping of function outputs to target node names\n",
        "            \"human_node\": \"human_node\",\n",
        "            \"ai_node\": \"ai_node\"\n",
        "        }\n",
        "    )\n",
        "\n",
        "    # Define terminal edges (where execution ends)\n",
        "    workflow.add_edge(\"ai_node\", END)\n",
        "    workflow.add_edge(\"human_node\", END)\n",
        "\n",
        "    # Compile into a Runnable\n",
        "    return workflow.compile()\n",
        "\n",
        "app = build_graph()\n",
        "print(\"LangGraph StateMachine compiled successfully!\")\n"
