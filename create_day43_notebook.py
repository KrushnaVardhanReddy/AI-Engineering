        "\n",
        "## Core Theory: The \"Why\" and \"How\" of LangGraph\n",
        "\n",
        "### The \"Why\"\n",
        "Traditional LangChain `Chain` objects or basic LCEL (LangChain Expression Language) graphs represent Directed Acyclic Graphs (DAGs). This means data flows from start to finish without loops. However, true *Agentic workflows* are almost never linear. Agents need to:\n",
        "1. Make a decision.\n",
        "2. Take an action (e.g., search the web).\n",
        "3. Observe the outcome.\n",
        "4. Loop back to step 1 to evaluate if more actions are needed or if they should return a final answer.\n",
        "\n",
        "**LangGraph** is built precisely for this. It extends LangChain to support stateful, cyclical workflows—the foundation of true autonomous agents.\n",
        "\n",
        "### The \"How\": State, Nodes, and Edges\n",
        "LangGraph models agent workflows as **State Machines** using three primary concepts:\n",
        "\n",
        "1.  **State (`State`):** A shared data structure (usually a `typing.TypedDict` or Pydantic model) that is passed around. Every node reads from it and writes updates to it. This is your agent's \"memory\" for the current run.\n",
        "2.  **Nodes (Functions):** Python functions that perform work. A node receives the current `State`, does something (calls an LLM, queries a DB, runs a tool), and returns a dictionary with *updates* to the state.\n",
        "3.  **Edges (Logic):** The routing rules. \n",
        "    *   *Normal Edges:* Always go from Node A to Node B.\n",
        "    *   *Conditional Edges:* Run a function to inspect the state and decide dynamically which node to go to next. This is how we implement \"if/else\" routing and loops.\n",
        "\n",
        "By structuring our application this way, we gain immense control, observability, and the ability to pause/resume execution (human-in-the-loop).\n"
