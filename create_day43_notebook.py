        "## Common Pitfalls in Production\n",
        "\n",
        "1.  **Infinite Loops (The Agent that never sleeps):**\n",
        "    *   *The Problem:* A cyclical graph where the `conditional_edge` never routes to `END`. The agent gets stuck iterating endlessly (costing you money via LLM token usage).\n",
        "    *   *The Solution:* Always implement a fallback or a hard counter (like `iterations` in the lab above) or use LangGraph's built-in `recursion_limit` parameter when invoking the graph (`app.invoke(state, config={\"recursion_limit\": 10})`).\n",
        "2.  **State Mutation Bugs (Appending vs Overwriting):**\n",
        "    *   *The Problem:* Standard `TypedDict` overwrites existing values. If you want to *append* to a list (like a message history), and you simply return `{\"messages\": [new_msg]}`, you will wipe out previous history.\n",
        "    *   *The Solution:* Use `typing.Annotated` with a reducer function (like `operator.add`) when defining the `State`, e.g., `messages: Annotated[list, add]`. This instructs LangGraph to append automatically.\n",
        "3.  **Missing Default Keys in State:**\n",
        "    *   *The Problem:* Accessing `state[\"missing_key\"]` in a node throws a `KeyError` if that key hasn't been set by an earlier node or initial state.\n",
        "    *   *The Solution:* Always initialize the full state schema upfront or use `state.get(\"key\", default_value)` defensively in your nodes."
